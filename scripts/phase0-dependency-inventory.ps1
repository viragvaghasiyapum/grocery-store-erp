param([string]$Repository = (Split-Path -Parent $PSScriptRoot))

$ErrorActionPreference = 'Stop'
$patterns = [ordered]@{
    'movement' = '\bstock_movement\b|\bStockLedger\b|\bIStockLedger\b'
    'lot quantity' = '\bqty_on_hand\b'
    'stock projection' = '\bproduct_stock_total\b|\bv_product_stock\b'
    'document status (inspect context)' = '\bstatus\b|\bSaleStatus\b|\bPurchaseStatus\b'
    'expiry (incl. UI)' = '\bexpir\w*|v_expiry_alert'
    'year lock' = '\bPeriodGuard\b|books\.locked_until|\bLockedUntil\b|\bEnsureOpen\s*\('
}
$rows = [System.Collections.Generic.List[object]]::new()
foreach ($folder in @('src', 'tests', 'tools', 'scripts')) {
    Get-ChildItem -LiteralPath (Join-Path $Repository $folder) -File -Recurse |
        Where-Object { $_.Extension -in @('.cs', '.xaml', '.sql', '.ps1') -and
            $_.FullName -notmatch '[\\/](?:bin|obj)[\\/]' -and
            $_.Name -ne 'phase0-dependency-inventory.ps1' } |
        ForEach-Object {
            $file = $_
            $relative = $file.FullName.Substring($Repository.TrimEnd('\', '/').Length + 1).Replace('\', '/')
            $number = 0
            foreach ($line in [IO.File]::ReadLines($file.FullName)) {
                $number++
                $hits = @($patterns.Keys | Where-Object { $line -match $patterns[$_] })
                if ($hits.Count -eq 0) { continue }
                $role = if ($relative -match '^tests/') { 'test' }
                    elseif ($relative -match '^(tools|scripts)/') { 'scale/generator/tool' }
                    elseif ($file.Extension -eq '.xaml' -or $relative -match '/Presentation/') { 'UI' }
                    elseif ($file.Extension -eq '.sql') { 'schema' }
                    elseif ($relative -match 'Backup|Restore') { 'backup/recovery' }
                    elseif ($relative -match 'Report|Export|Output') { 'report/export' }
                    elseif ($relative -match 'Migration|Maintenance|Startup') { 'migration/startup/maintenance' }
                    elseif ($line -match '\b(INSERT|UPDATE|DELETE|WriteAsync|Execute)\b|\.Post\(') { 'writer' }
                    else { 'reader/service' }
                $rows.Add([pscustomobject]@{ File = $relative; Line = $number; Role = $role; Hits = ($hits -join ', ') })
            }
        }
}
foreach ($file in @(Get-Item -LiteralPath (Join-Path $Repository 'grocery_erp_schema.sql')) +
    @(Get-ChildItem -LiteralPath $Repository -File | Where-Object { $_.Name -match '^\d{3}_.+\.sql$' })) {
    $relative = $file.Name
    $number = 0
    foreach ($line in [IO.File]::ReadLines($file.FullName)) {
        $number++
        $hits = @($patterns.Keys | Where-Object { $line -match $patterns[$_] })
        if ($hits.Count -gt 0) {
            $rows.Add([pscustomobject]@{ File = $relative; Line = $number; Role = 'shipped schema/trigger/view'; Hits = ($hits -join ', ') })
        }
    }
}
$destination = Join-Path $Repository 'docs/phase0/dependency-inventory.md'
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
$output = [System.Collections.Generic.List[string]]::new()
$output.Add('# Phase 0 dependency inventory')
$output.Add('')
$output.Add('Generated by `scripts/phase0-dependency-inventory.ps1`. Every textual source hit in active source, tests, tools, scripts and shipped SQL is listed. SQL continuation lines and indirect calls require the manual map in `behavior-matrix.md`. Shipped migrations 002–028 are immutable. A missing textual hit does not prove absence of a dependency.')
$output.Add('')
$output.Add("Total source hits: **$($rows.Count)** in **$(@($rows.File | Sort-Object -Unique).Count)** files.")
$output.Add('')
$output.Add('| File:line | Role | Reference |')
$output.Add('|---|---|---|')
foreach ($row in $rows | Sort-Object File, Line) {
    $output.Add("| ``$($row.File):$($row.Line)`` | $($row.Role) | $($row.Hits) |")
}
[IO.File]::WriteAllLines($destination, $output, [Text.UTF8Encoding]::new($false))
Write-Output "Wrote $($rows.Count) hits to $destination"
